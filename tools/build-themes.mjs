#!/usr/bin/env node
// SPDX-License-Identifier: MIT
// Generates js/themes.generated.js from an Omarchy installation's themes.
//
// Each theme in /usr/share/omarchy/themes (or $OMARCHY_THEMES) ships a
// colors.toml; this reads the colour tokens out of it so the demo recolours
// itself with the same values Omarchy uses. Run it again after a theme
// update:
//
//   node tools/build-themes.mjs
//
// Omit a theme by listing it in THEME_SKIP; the order in THEME_ORDER is the
// order the picker shows them in.

import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs"
import { join, dirname } from "node:path"
import { fileURLToPath } from "node:url"

const root = join(dirname(fileURLToPath(import.meta.url)), "..")
const themesDir = process.env.OMARCHY_THEMES || "/usr/share/omarchy/themes"

const THEME_ORDER = [
  "tokyo-night",
  "catppuccin",
  "kanagawa",
  "everforest",
  "gruvbox",
  "rose-pine",
  "nord",
  "ethereal",
  "miasma",
  "ristretto",
  "lupine",
  "solitude",
  "osaka-jade",
  "matte-black",
  "vantablack",
  "flexoki-light",
  "catppuccin-latte",
  "white",
]

const THEME_SKIP = new Set(["hackerman", "jade-horse", "last-horizon", "lumon", "retro-82", "starship"])

// The tokens the demo style sheet consumes. Anything else in colors.toml is
// kept as-is so future use needs no regeneration.
function parseColors(text) {
  const out = {}
  for (const raw of text.split("\n")) {
    const line = raw.trim()
    if (!line || line.startsWith("#")) continue
    const m = line.match(/^([A-Za-z0-9_]+)\s*=\s*"([^"]*)"/)
    if (m) out[m[1]] = m[2]
  }
  return out
}

function titleOf(id) {
  return id
    .split("-")
    .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
    .join(" ")
}

if (!existsSync(themesDir)) {
  console.error(`build-themes: ${themesDir} not found; set OMARCHY_THEMES`)
  process.exit(1)
}

const found = readdirSync(themesDir, { withFileTypes: true })
  .filter((d) => d.isDirectory() && !THEME_SKIP.has(d.name))
  .map((d) => d.name)
  .filter((d) => existsSync(join(themesDir, d, "colors.toml")))

const rank = (id) => {
  const i = THEME_ORDER.indexOf(id)
  return i === -1 ? 100 + id.charCodeAt(0) : i
}
found.sort((a, b) => rank(a) - rank(b) || a.localeCompare(b))

const themes = found.map((id) => {
  const colors = parseColors(readFileSync(join(themesDir, id, "colors.toml"), "utf8"))
  return {
    id,
    name: colors.name || titleOf(id),
    mode: colors.mode === "light" ? "light" : "dark",
    colors,
  }
})

const banner = `// Generated by tools/build-themes.mjs from ${themesDir}. Do not edit by hand.
// SPDX-License-Identifier: MIT
`

const body = `${banner}export const THEMES = ${JSON.stringify(themes, null, 2)}\n\nexport const DEFAULT_THEME = ${JSON.stringify(themes[0]?.id || "tokyo-night")}\n`

writeFileSync(join(root, "js/themes.generated.js"), body)
console.log(`build-themes: wrote ${themes.length} themes (${themes.map((t) => t.id).join(", ")})`)
